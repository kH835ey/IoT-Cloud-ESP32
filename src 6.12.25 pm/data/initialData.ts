export function generateInitialTelemetryHistory(count = 30): TelemetryPoint[] {
  const points: TelemetryPoint[] = [];
  const now = Date.now();
  const stepMs = 2000; // 2s steps for real-time fidelity

  for (let i = count; i >= 0; i--) {
    const time = now - i * stepMs;
    const dateObj = new Date(time);
    const timeStr = dateObj.toLocaleTimeString('en-US', { hour12: false, hour: '2-digit', minute: '2-digit', second: '2-digit' });

    points.push({
      timestamp: time,
      timeStr,
      temperature: 0,
      humidity: 0,
      gasCo: 0,
      soilMoisture: 0,
      fanSpeed: 0,
      relay1: 0,
      relay2: 0,
    });
  }

  return points;
}

